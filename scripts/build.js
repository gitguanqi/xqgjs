#!/usr/bin/env node
/**
 * Regenerates the committed *.min.js / *.min.css artifacts from the readable sources.
 *
 * The package ships its build output, so a source edit is incomplete until the matching
 * minified file is regenerated. A real minifier is required: a regex tidier corrupts the
 * Chinese comments and the nested closures in this code.
 *
 * Usage:
 *   node scripts/build.js            # rewrite the minified artifacts
 *   node scripts/build.js --check    # fail if any committed artifact is stale
 *
 * Two deliberate choices:
 *   - bundle: false, so esbuild never wraps the file in its own IIFE. The UMD header must
 *     survive verbatim, and the ESM build must keep `export default`.
 *   - charset: utf8, otherwise every non-ASCII comment becomes a \u escape and the diff
 *     stops being reviewable.
 */

'use strict';

const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const ROOT = path.resolve(__dirname, '..');
const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));

const TARGETS = [
    { src: 'lib/xqgjs.js', out: 'lib/xqgjs.min.js', kind: 'umd' },
    { src: 'lib/xqgjs-esm.js', out: 'lib/xqgjs-esm.min.js', kind: 'esm' },
    { src: 'lib/loading/js/loading.js', out: 'lib/loading/js/loading.min.js', kind: 'script' },
    { src: 'lib/mourn/mourn.js', out: 'lib/mourn/mourn.min.js', kind: 'script' },
    { src: 'lib/loading/css/loading.css', out: 'lib/loading/css/loading.min.css', kind: 'css' }
];

function loadEsbuild() {
    try {
        return require('esbuild');
    } catch (error) {
        console.error('esbuild is required. Run `npm install` first.');
        process.exit(1);
    }
}

function banner(target) {
    return '/*! xqgjs v' + pkg.version + ' | ' + pkg.license +
        ' | ' + target.src + ' -> ' + target.out +
        ' | generated by scripts/build.js, do not edit */\n';
}

function minify(esbuild, target) {
    const absoluteSrc = path.join(ROOT, target.src);
    if (!fs.existsSync(absoluteSrc)) {
        throw new Error('missing source: ' + target.src);
    }

    const options = {
        entryPoints: [absoluteSrc],
        outfile: path.join(ROOT, target.out),
        bundle: false,
        write: false,
        minify: true,
        legalComments: 'none',
        logLevel: 'silent'
    };

    if (target.kind === 'css') {
        options.banner = { css: banner(target) };
    } else {
        options.target = 'es2017';
        options.charset = 'utf8';
        options.keepNames = true;
        options.banner = { js: banner(target) };
    }

    const result = esbuild.buildSync(options);
    if (!result.outputFiles || !result.outputFiles.length) {
        throw new Error('esbuild produced no output for ' + target.src);
    }
    return result.outputFiles[0].text;
}

// Text-level contract checks. Semantic checks (same exports, same API surface) live in
// test/unit/contract.test.js, which actually executes each artifact.
function assertMarkers(code, target) {
    const problems = [];
    const require_ = (re, label) => {
        if (!re.test(code)) problems.push('missing ' + label);
    };
    const forbid = (re, label) => {
        if (re.test(code)) problems.push('unexpected ' + label);
    };

    if (target.kind === 'umd') {
        require_(/module\.exports\s*=/, 'module.exports branch');
        require_(/define\.amd/, 'AMD branch');
        require_(/\.gjs\s*=/, 'global gjs assignment');
        require_(/\.\$g\s*=/, 'global $g assignment');
        forbid(/export\s+default/, 'ESM export in a UMD build');
    } else if (target.kind === 'esm') {
        require_(/export\s*\{[^}]*\bas\s+default\b|export\s+default\b/, 'default export');
        forbid(/module\.exports/, 'CommonJS export in an ESM build');
        forbid(/\.gjs\s*=\s*factory/, 'global assignment in an ESM build');
    } else if (target.kind === 'script') {
        // Parsing is cheap and catches a minifier that produced broken syntax.
        try {
            new vm.Script(code, { filename: target.out });
        } catch (error) {
            problems.push('does not parse: ' + error.message);
        }
    } else if (target.kind === 'css') {
        forbid(/\bundefined\b/, 'undefined in a stylesheet');
    }

    if (problems.length) {
        throw new Error(target.out + ': ' + problems.join('; '));
    }
}

function main(argv) {
    const check = argv.includes('--check');
    const esbuild = loadEsbuild();
    const stale = [];
    const written = [];

    for (const target of TARGETS) {
        let code;
        try {
            code = minify(esbuild, target);
            assertMarkers(code, target);
        } catch (error) {
            console.error('BUILD FAILED  ' + target.out);
            console.error('  ' + error.message);
            process.exit(1);
        }

        const absoluteOut = path.join(ROOT, target.out);

        if (check) {
            const actual = fs.existsSync(absoluteOut) ? fs.readFileSync(absoluteOut, 'utf8') : '';
            if (actual !== code) {
                stale.push(target.out);
                console.log('STALE         ' + target.out);
            } else {
                console.log('up-to-date    ' + target.out);
            }
        } else {
            fs.mkdirSync(path.dirname(absoluteOut), { recursive: true });
            fs.writeFileSync(absoluteOut, code, 'utf8');
            written.push(target.out);
            console.log('wrote         ' + target.out + '  (' + Buffer.byteLength(code, 'utf8') + ' bytes)');
        }
    }

    if (check && stale.length) {
        console.error('\n' + stale.length + ' artifact(s) out of date. Run `npm run build`.');
        process.exit(1);
    }

    if (!check) {
        console.log('\n' + written.length + ' artifact(s) regenerated from source.');
    }
}

main(process.argv.slice(2));
