'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {
    ROOT,
    absolute,
    read,
    loadUMD,
    loadESM,
    UMD_READABLE,
    UMD_MIN,
    ESM_READABLE,
    ESM_MIN
} = require('./helpers/sandbox');
const { plain } = require('./helpers/plain');

const pkg = JSON.parse(read('package.json'));

const SHIPPED = [
    UMD_READABLE,
    UMD_MIN,
    ESM_READABLE,
    ESM_MIN,
    'lib/loading/js/loading.js',
    'lib/loading/js/loading.min.js',
    'lib/loading/css/loading.css',
    'lib/loading/css/loading.min.css',
    'lib/mourn/mourn.js',
    'lib/mourn/mourn.min.js'
];

function decodeStrict(relative) {
    const buffer = fs.readFileSync(absolute(relative));
    return new TextDecoder('utf-8', { fatal: true }).decode(buffer);
}

test('every shipped text file is valid UTF-8 without a BOM', () => {
    for (const file of SHIPPED) {
        const text = decodeStrict(file);
        assert.notEqual(text.charCodeAt(0), 0xfeff, file + ' must not start with a BOM');
        assert.ok(text.length > 0, file + ' must not be empty');
    }
});

test('non-ASCII comments survived the pipeline', () => {
    const source = read(UMD_READABLE);
    assert.ok(source.includes('获取成功'), 'Chinese strings must not be escaped away');
    const loading = read('lib/loading/js/loading.js');
    assert.ok(loading.includes('图标颜色'));
});

test('the UMD builds keep their module shape', () => {
    for (const file of [UMD_READABLE, UMD_MIN]) {
        const code = read(file);
        assert.match(code, /module\.exports\s*=/, file);
        assert.match(code, /define\.amd/, file);
        assert.match(code, /\.gjs\s*=/, file);
        assert.doesNotMatch(code, /export\s+default/, file + ' must not contain an ESM export');
    }
});

test('the ESM builds keep their module shape', () => {
    for (const file of [ESM_READABLE, ESM_MIN]) {
        const code = read(file);
        assert.match(code, /export\s*\{[^}]*\bas\s+default\b|export\s+default\b/, file);
        assert.doesNotMatch(code, /module\.exports/, file + ' must not contain a CommonJS export');
        assert.doesNotMatch(code, /\.gjs\s*=\s*factory/, file + ' must not assign a global');
    }
});

test('the minified files carry a banner that names their source', () => {
    for (const file of [UMD_MIN, ESM_MIN, 'lib/loading/js/loading.min.js', 'lib/mourn/mourn.min.js']) {
        const code = read(file);
        assert.match(code, /^\/\*! xqgjs v/, file + ' should start with the banner');
        assert.ok(code.includes('generated by scripts/build.js'), file);
    }
});

test('no known anti-pattern came back', () => {
    const checks = [
        [/\bfor \(name in/, 'undeclared loop variable'],
        [/\bmeida\b/, 'misspelled this.media'],
        [/(^|[^.\w])zhEnReg\.test/, 'bare regex identifier'],
        [/(^|[^.\w])emailReg\.test/, 'bare regex identifier'],
        [/elem\.classList\s*=\s*[^=]/, 'assigning the read-only classList'],
        [/\bwindow\.gjs\s*=\s*\$g\s*=/, 'implicit global assignment']
    ];
    for (const file of [UMD_READABLE, ESM_READABLE]) {
        const code = read(file);
        for (const [pattern, label] of checks) {
            assert.doesNotMatch(code, pattern, file + ' still has ' + label);
        }
    }
});

test('package.json describes a loadable package', () => {
    for (const field of ['main', 'module', 'types', 'unpkg']) {
        assert.ok(pkg[field], field + ' must be set');
        assert.ok(fs.existsSync(absolute(pkg[field])), field + ' points at a missing file: ' + pkg[field]);
    }

    assert.ok(Array.isArray(pkg.files) && pkg.files.includes('lib'), 'files must whitelist lib');
    assert.ok(!pkg.files.some((entry) => entry.startsWith('test')), 'test must not be published');
});

test('the exports map puts types first and keeps deep paths working', () => {
    const root = pkg.exports['.'];
    assert.deepEqual(Object.keys(root.import), ['types', 'default'], 'types must come first');
    assert.deepEqual(Object.keys(root.require), ['types', 'default']);
    assert.ok(root.import.types.endsWith('.d.mts'), 'the ESM condition needs an ESM declaration file');
    assert.ok(pkg.exports['./lib/*'], 'legacy deep imports must keep resolving');
    assert.ok(fs.existsSync(absolute(root.import.types)));
    assert.ok(fs.existsSync(absolute(root.require.types)));
});

test('the announced version matches the code', () => {
    const umd = read(UMD_READABLE);
    const version = /version:\s*'([^']+)'/.exec(umd);
    assert.ok(version, 'info.version must exist');
    assert.equal(version[1], 'v' + pkg.version, 'Gjs.info.version must match package.json');

    const banner = read(UMD_MIN);
    assert.ok(banner.includes('v' + pkg.version), 'the banner must mention the same version');
});

test('the release date is the same in both builds and both documents', () => {
    const umd = /date:\s*'(\d{4}-\d{2}-\d{2})'/.exec(read(UMD_READABLE));
    const esm = /date:\s*'(\d{4}-\d{2}-\d{2})'/.exec(read(ESM_READABLE));
    assert.ok(umd && esm);
    assert.equal(esm[1], umd[1], 'the two builds must agree on the date');

    for (const doc of ['README.md', 'zh.md']) {
        const text = read(doc);
        assert.ok(text.includes(umd[1]), doc + ' still documents an old date');
        assert.ok(text.includes("version: 'v" + pkg.version + "'"), doc + ' still documents an old version');
    }
});

test('the test script does not fail by construction', () => {
    assert.doesNotMatch(pkg.scripts.test, /exit 1/, 'a placeholder that always fails makes CI meaningless');
    assert.match(pkg.scripts.test, /test:unit/);
    assert.doesNotMatch(pkg.scripts['test:browser'], /live-server/, 'the server must be local to the repo');
});

test('the loading stylesheet covers every class the script creates', () => {
    const js = read('lib/loading/js/loading.js');
    const css = read('lib/loading/css/loading.css');
    const classes = new Set();
    const pattern = /classList\.add\('([\w-]+)'\)|className\s*=\s*'([\w\s-]+)'/g;
    let match;
    while ((match = pattern.exec(js)) !== null) {
        const names = (match[1] || match[2] || '').split(/\s+/).filter(Boolean);
        for (const name of names) classes.add(name);
    }
    for (const name of classes) {
        assert.ok(css.includes('.' + name), 'loading.css has no rule for .' + name);
    }
});

test('every shipped artifact loads and exposes the same API', async () => {
    const umdReadable = loadUMD(UMD_READABLE).gjs;
    const umdMin = loadUMD(UMD_MIN).gjs;
    const esmReadable = (await loadESM(ESM_READABLE)).gjs;
    const esmMin = (await loadESM(ESM_MIN)).gjs;

    const expected = Object.keys(umdReadable).sort();
    for (const [label, value] of [['umd.min', umdMin], ['esm', esmReadable], ['esm.min', esmMin]]) {
        assert.deepEqual(Object.keys(value).sort(), expected, label + ' static surface');
        assert.deepEqual(plain(value.info), plain(umdReadable.info), label + ' info');
        assert.equal(value.fn.init.prototype, value.fn, label + ' prototype chain');
    }
});

test('the test index links every page that exists', (t) => {
    const indexPath = absolute('test/index.html');
    if (!fs.existsSync(indexPath)) {
        t.skip('test/index.html has not been written yet');
        return;
    }
    const index = fs.readFileSync(indexPath, 'utf8');
    const pages = fs.readdirSync(path.join(ROOT, 'test'))
        .filter((name) => name.endsWith('.html') && name !== 'index.html');
    for (const page of pages) {
        assert.ok(index.includes(page), 'test/index.html does not link ' + page);
    }
});
